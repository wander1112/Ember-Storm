"""
Visualizations Gallery & Reports Module
Supports interactive visualization inspection, summary export, and dataset download.
"""

import pandas as pd
import numpy as np

def generate_markdown_report(dataset_summary, model_results_dict, best_models_dict):
    """
    Compile a complete Markdown report summarizing dataset audits, preprocessing, and model benchmarks.
    """
    report = []
    report.append("# ML Studio — Machine Learning Project Summary Report\n")
    report.append("Generated by **ML Studio Analytics Platform**\n\n---\n")
    
    # 1. Dataset Overview
    report.append("## 1. Dataset Overview\n")
    if dataset_summary:
        report.append(f"- **Total Rows:** {dataset_summary.get('total_rows', 'N/A')}\n")
        report.append(f"- **Total Features:** {dataset_summary.get('total_features', 'N/A')}\n")
        report.append(f"- **Numerical Columns:** {len(dataset_summary.get('num_cols', []))}\n")
        report.append(f"- **Categorical Columns:** {len(dataset_summary.get('cat_cols', []))}\n")
        report.append(f"- **Missing Value Count:** {dataset_summary.get('total_missing', 0)} ({dataset_summary.get('missing_pct', 0)}%)\n")
        report.append(f"- **Duplicate Rows:** {dataset_summary.get('duplicate_rows', 0)}\n")
        report.append(f"- **Detected Outliers (IQR):** {dataset_summary.get('total_outliers', 0)}\n\n")
        
    # 2. Model Performance Summaries
    report.append("## 2. Model Benchmark Summaries\n")
    for track, df in model_results_dict.items():
        if df is not None and not df.empty:
            report.append(f"### {track} Track Results\n")
            report.append(df.to_markdown(index=False) + "\n\n")
            
            if track in best_models_dict:
                best_info = best_models_dict[track]
                report.append(f"**Top Performing Model:** {best_info.get('name')}\n")
                report.append(f"{best_info.get('explanation')}\n\n")
                
    report.append("---\n*End of Report*\n")
    return "".join(report)
